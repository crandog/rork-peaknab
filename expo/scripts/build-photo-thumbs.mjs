/**
 * Build lightweight bundled versions of the mountain hero photos.
 *
 * Reads the id -> remote URL mapping in constants/mountainImages.ts, downloads
 * each unique photo, encodes a 720px-wide WebP copy into
 * assets/images/photo-thumbs/, and (re)generates constants/mountainPhotoThumbs.ts
 * with an explicit mountain-ID -> bundled-asset mapping.
 *
 * Run with: bun expo/scripts/build-photo-thumbs.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE = path.join(ROOT, 'constants/mountainImages.ts');
const OUT_DIR = path.join(ROOT, 'assets/images/photo-thumbs');
const MAPPING_OUT = path.join(ROOT, 'constants/mountainPhotoThumbs.ts');

const WIDTH = 720;
const QUALITY = 72;
const CONCURRENCY = 8;

const source = fs.readFileSync(SOURCE, 'utf8');
const entries = [...source.matchAll(/'([^']+)':\s*'(https:[^']+)'/g)];
if (entries.length === 0) throw new Error('No mountain image entries parsed');

// First id that uses a URL owns the file name; other ids alias to it.
const fileForUrl = new Map();
for (const [, id, url] of entries) {
  if (!fileForUrl.has(url)) fileForUrl.set(url, id);
}

const jobs = [];
for (const [, id, url] of entries) {
  const fileId = fileForUrl.get(url);
  jobs.push({ id, url, file: `${fileId}.webp` });
}
const uniqueJobs = [...fileForUrl.entries()].map(([url, id]) => ({ id, url, file: `${id}.webp` }));

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.mkdirSync('/tmp/peaknab-thumbs/orig', { recursive: true });

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
}

async function processOne(job) {
  const ext = path.extname(new URL(job.url).pathname) || '.png';
  const orig = path.join('/tmp/peaknab-thumbs/orig', `${job.id}${ext}`);
  await download(job.url, orig);
  const out = path.join(OUT_DIR, job.file);
  execFileSync('ffmpeg', [
    '-y', '-loglevel', 'error', '-i', orig,
    '-vf', `scale=${WIDTH}:-2`,
    '-c:v', 'libwebp', '-q:v', String(QUALITY), '-compression_level', '6',
    out,
  ]);
  return fs.statSync(out).size;
}

const failures = [];
let index = 0;
async function worker() {
  while (index < uniqueJobs.length) {
    const job = uniqueJobs[index++];
    try {
      job.bytes = await processOne(job);
    } catch (e) {
      failures.push({ id: job.id, url: job.url, error: String(e) });
    }
  }
}
await Promise.all(Array.from({ length: CONCURRENCY }, worker));

const succeeded = uniqueJobs.filter((j) => j.bytes != null);
const totalBytes = succeeded.reduce((sum, j) => sum + j.bytes, 0);

// Only ids whose photo was successfully built get a mapping entry; the rest
// keep remote-only loading in the app (never substitute another photo).
const okFiles = new Set(succeeded.map((j) => j.file));
const mapping = jobs
  .filter((j) => okFiles.has(j.file))
  .map((j) => `  '${j.id}': require('../assets/images/photo-thumbs/${j.file}'),`);

const generated = `/**
 * AUTO-GENERATED by scripts/build-photo-thumbs.mjs — do not edit by hand.
 *
 * Lightweight local copies (${WIDTH}px WebP, q${QUALITY}) of the mountain hero
 * photos, keyed by mountain ID. Used as the immediate on-device photo on the
 * mountain detail page while the full-resolution remote version loads; the
 * remote version is then kept in disk cache for repeat visits.
 *
 * Ids without a bundled photo (e.g. custom peaks) are intentionally absent —
 * they fall back to remote loading only.
 */
/* eslint-disable global-require */

export const mountainPhotoThumbs: Record<string, number> = {
${mapping.join('\n')}
};

/** Bundled lightweight photo for a mountain id, or undefined when absent. */
export function getMountainPhotoThumb(mountainId: string): number | undefined {
  return mountainPhotoThumbs[mountainId];
}
`;

fs.writeFileSync(MAPPING_OUT, generated);

console.log(`Mountains: ${jobs.length} ids, ${uniqueJobs.length} unique photos`);
console.log(`Built: ${succeeded.length}, failed: ${failures.length}`);
console.log(`Total bundled size: ${(totalBytes / 1024 / 1024).toFixed(2)} MB (${totalBytes} bytes)`);
for (const f of failures) console.log(`FAILED ${f.id}: ${f.error}`);
if (failures.length > 0) process.exitCode = 1;
